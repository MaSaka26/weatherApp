/**
 * 中文地名的简 -> 繁逐字映射（精简版，覆盖常见境外城市译名差异字）。
 *
 * 背景：Open-Meteo 地理编码库里，部分境外城市的中文名存的是繁体：
 * 英国伦敦「倫敦」、日本东京「東京」、纽约「紐約」、剑桥「劍橋」…
 * 用户用简体「伦敦 / 东京」查，language=zh 只能命中加拿大/美国/中国境内的同名地，
 * 真正想要的英/日大城市反而漏掉。多查一路繁体变体即可补齐，零外部依赖。
 *
 * 只收录确实发生字形变化的字；表里没有的字（敦、京、尼、加…）原样保留。
 * 刻意保持小体积、可单测，不做完整简繁转换。
 */
const S2T = {
  伦: '倫', 东: '東', 纽: '紐', 剑: '劍', 桥: '橋',
  华: '華', 约: '約', 汉: '漢', 马: '馬', 国: '國',
  湾: '灣', 台: '臺', 兰: '蘭', 顿: '頓', 罗: '羅',
  苏: '蘇', 温: '溫', 尔: '爾', 纳: '納', 维: '維',
  开: '開', 内: '內', 奥: '奧', 灵: '靈', 彻: '徹',
  滨: '濱', 横: '橫', 户: '戶', 广: '廣', 岛: '島',
  长: '長', 冈: '岡', 买: '買', 达: '達', 鲁: '魯',
  亚: '亞', 图: '圖', 费: '費', 迈: '邁',
}

/** 生成繁体变体；与原词相同则返回空串（避免重复请求） */
export function toTraditional(query) {
  if (!query) return ''
  let out = ''
  let changed = false
  for (const ch of query) {
    const t = S2T[ch]
    if (t) { out += t; if (t !== ch) changed = true }
    else out += ch
  }
  return changed ? out : ''
}

/** 是否含中文字符（只有中文输入才值得查繁体变体） */
export function hasChinese(query) {
  return /[\u4e00-\u9fff]/.test(query || '')
}
